#!/usr/bin/env python3
"""Run the Hindi language/culture/idiom evaluation on one checkpoint.

Evaluates a HuggingFace causal-LM checkpoint (base or continued-pretrained) on
any subset of {mabl, milu, global_piqa, idiomce} and writes per-task result
JSON + a summary.json under ``--output_dir``.

Multiple-choice tasks (mabl, milu, global_piqa) are scored with base-model
log-likelihood (acc + length-normalized acc_norm). IdiomCE is generated by the
checkpoint and graded by an OpenAI judge model.

Example (run twice, once per checkpoint, then compare_results.py):

    python -m culture.evaluation.run_eval \\
        --model_path /lustre/.../ckpts/qwen3p5-9b-hi-cpt \\
        --tasks mabl,milu,global_piqa,idiomce \\
        --mabl_path   data/eval/hi/mabl_hi.csv \\
        --global_piqa_path data/eval/hi/global_piqa_hi.tsv \\
        --idiomce_path data/eval/hi/idiomce_hi.jsonl \\
        --judge_model gpt-4o \\
        --output_dir results/hi/cpt
"""

import argparse
import json
import logging
import os
import sys
from pathlib import Path
from typing import Any, Dict, List

# Allow `python src/culture/evaluation/run_eval.py` without install.
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from culture.evaluation.scorer import HFModel
from culture.evaluation.tasks import LOADERS, GenTask, MCTask
from culture.evaluation.tasks_zh import LOADERS_ZH
from culture.evaluation.tasks_ar import LOADERS_AR

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
logger = logging.getLogger("culture.eval")

# Merge the per-language loaders into the shared registry
# (Hindi + English + Chinese + Arabic).
LOADERS = {**LOADERS, **LOADERS_ZH, **LOADERS_AR}

MC_TASKS = {"mabl", "milu", "global_piqa", "mmlu", "boolq",
            "chid", "chengyu_bench", "cmmlu", "ccpm",
            *LOADERS_AR}
GEN_TASKS = {"idiomce"}


# --------------------------------------------------------------------------- #
# Multiple-choice evaluation
# --------------------------------------------------------------------------- #
def eval_mc(model: HFModel, task: MCTask, batch_size: int) -> Dict[str, Any]:
    # Flatten every (context, option) into one request list.
    requests, spans = [], []
    for ex in task.examples:
        start = len(requests)
        for opt in ex.options:
            requests.append((ex.context, opt))
        spans.append((start, len(requests)))

    results = model.loglikelihood(requests, batch_size=batch_size)

    n_correct = n_correct_norm = 0
    records: List[Dict[str, Any]] = []
    for ex, (s, e) in zip(task.examples, spans):
        opt_res = results[s:e]
        sums = [r.logprob for r in opt_res]
        norms = [r.logprob_per_token for r in opt_res]
        pred = int(max(range(len(sums)), key=lambda i: sums[i]))
        pred_norm = int(max(range(len(norms)), key=lambda i: norms[i]))
        correct = int(pred == ex.gold)
        correct_norm = int(pred_norm == ex.gold)
        n_correct += correct
        n_correct_norm += correct_norm
        records.append({
            "qid": ex.qid, "gold": ex.gold, "pred": pred, "pred_norm": pred_norm,
            "correct": correct, "correct_norm": correct_norm,
            "logprobs": [round(x, 4) for x in sums],
            "logprobs_norm": [round(x, 4) for x in norms],
            **ex.meta,
        })

    n = len(task.examples)
    metrics = {
        "task": task.name, "n": n, "score_mode": task.score_mode,
        "acc": round(n_correct / n, 4) if n else None,
        "acc_norm": round(n_correct_norm / n, 4) if n else None,
    }
    # For letter-scored tasks acc == acc_norm (single token); report acc.
    metrics["primary"] = metrics["acc"] if task.score_mode == "letter" else metrics["acc_norm"]
    return {"metrics": metrics, "records": records}


# --------------------------------------------------------------------------- #
# Generation + judge evaluation (IdiomCE)
# --------------------------------------------------------------------------- #
def eval_gen(model: HFModel, task: GenTask, args) -> Dict[str, Any]:
    prompts = [ex.prompt for ex in task.examples]
    hyps = model.generate(
        prompts,
        max_new_tokens=args.max_new_tokens,
        batch_size=args.gen_batch_size,
        stop=["\n", "English:"],
    )
    records = [{
        "qid": ex.qid, "source": ex.source, "hypothesis": hyp,
        "reference": ex.reference, "idiom_en": ex.idiom_en, "idiom_hi": ex.idiom_hi,
    } for ex, hyp in zip(task.examples, hyps)]

    if args.no_judge:
        logger.warning("--no_judge set: emitting translations without scoring.")
        return {"metrics": {"task": task.name, "n": len(records), "judged": False},
                "records": records}

    logger.info("Judging %d translations with %s (%s)", len(records),
                args.judge_model, args.judge_provider)
    from culture.evaluation import judge as judge_mod  # lazy: only needs openai when judging
    judged = judge_mod.judge_translations(
        records, judge_model=args.judge_model, provider=args.judge_provider,
        batch_size=args.judge_batch_size,
    )
    agg = judge_mod.aggregate(judged)
    metrics = {"task": task.name, "judged": True, **agg,
               "primary": agg["idiom_score_mean"]}
    return {"metrics": metrics, "records": judged}


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model_path", required=True, help="Local path or HF id of the checkpoint under test.")
    p.add_argument("--tasks", default="mabl,milu,global_piqa,idiomce",
                   help="Comma-separated subset of {mabl,milu,global_piqa,idiomce}.")
    p.add_argument("--output_dir", required=True)
    p.add_argument("--run_name", default=None, help="Label stored in summary.json (default: model dir name).")

    # Per-task local data paths (see README for schemas).
    p.add_argument("--mabl_path", default=None)
    p.add_argument("--milu_path", default=None, help="Local MILU test file; else HF ai4bharat/MILU.")
    p.add_argument("--milu_fewshot_path", default=None, help="MILU validation file for few-shot exemplars.")
    p.add_argument("--global_piqa_path", default=None, help="Local Global PIQA TSV; else HF.")
    p.add_argument("--idiomce_path", default=None)
    p.add_argument("--mmlu_path", default=None, help="Local MMLU file; else HF cais/mmlu (config all).")
    p.add_argument("--boolq_path", default=None, help="Local BoolQ file; else HF google/boolq.")

    # Chinese tasks (see docs/plans/eval_benchmarks_download.md + download_zh.sh).
    p.add_argument("--chid_path", default=None, help="Local ChID jsonl; else HF thu-coai/chid (validation).")
    p.add_argument("--chid_answer_path", default=None,
                   help="ChID answer file (chujiezheng/ChID-Dataset *_answer.json/csv); "
                        "REQUIRED for scorable ChID — the HF mirror ships no gold.")
    p.add_argument("--chengyu_bench_dir", default=None,
                   help="Cloned sofyc/ChengyuBench repo dir (Chengyu-Bench).")
    p.add_argument("--chengyu_bench_subtask", default="connotation",
                   choices=["connotation", "appropriateness"],
                   help="Chengyu-Bench binary subtask.")
    p.add_argument("--cmmlu_subjects", default=None,
                   help="Comma-separated CMMLU subject configs (default: 16 China-specific).")
    p.add_argument("--cmmlu_dir", default=None,
                   help="Local CMMLU dir (<dir>/test/<subject>.csv, <dir>/dev/<subject>.csv) "
                        "from `hf download haonan-li/cmmlu`; bypasses the dead HF script loader.")
    p.add_argument("--ccpm_path", default=None,
                   help="Local CCPM jsonl (git clone THUNLP-AIPoet/CCPM).")

    # Arabic (dimension 3+4) — one root dir drives every Arabic task.
    p.add_argument("--ar_data_dir", default=None,
                   help="Root of the Arabic benchmark tree written by download_ar.sh "
                        "(default data/eval/ar/raw).")
    p.add_argument("--ar_kb_path", default=None,
                   help="Arabic idiom KB jsonl. If given, examples whose stem contains a "
                        "KB idiom surface are DROPPED (belt-and-braces decontamination; "
                        "measured impact is <1%% on Alyah/DziriEval).")
    p.add_argument("--arabculture_countries", default=None,
                   help="Comma-separated ArabCulture countries (default: all 13).")
    p.add_argument("--acqa_dialects", default="msa",
                   help="ArabicCulturalQA dialect variants: msa|egyptian|gulf|levantine|"
                        "maghrebi|english, comma-separated, or 'all'.")
    p.add_argument("--arabicmmlu_subjects", default=None,
                   help="Comma-separated ArabicMMLU subjects, or 'all' (default: the 13 "
                        "Arab-region subjects, 10,529 rows).")
    p.add_argument("--global_piqa_ar_all", action="store_true",
                   help="Keep Global-PIQA Arabic items with approx_cultural_score != 1 "
                        "(default: culturally-scored items only).")
    p.add_argument("--ar_num_fewshot", type=int, default=0,
                   help="Few-shot for the Arabic tasks (0 = zero-shot, matching zh/hi).")
    p.add_argument("--kinayat_symmetric", action="store_true",
                   help="Restrict kinayat_cloze to the 116 items where the gold and the "
                        "distractor idiom have the SAME training-KB status, so neither "
                        "option gets more CPT exposure. Requires --ar_kb_path.")

    # Prompting / scoring.
    p.add_argument("--num_fewshot", type=int, default=0, help="Few-shot for MABL/Global PIQA.")
    p.add_argument("--milu_num_fewshot", type=int, default=5)
    p.add_argument("--cmmlu_num_fewshot", type=int, default=5)
    p.add_argument("--limit", type=int, default=None, help="Cap examples per task (debug).")
    p.add_argument("--seed", type=int, default=42)

    # Model.
    p.add_argument("--dtype", default="bfloat16")
    p.add_argument("--max_length", type=int, default=4096)
    p.add_argument("--batch_size", type=int, default=8, help="Log-likelihood batch size.")

    # Generation + judge (IdiomCE).
    p.add_argument("--max_new_tokens", type=int, default=128)
    p.add_argument("--gen_batch_size", type=int, default=8)
    p.add_argument("--judge_model", default="gpt-4o")
    p.add_argument("--judge_provider", default="openai")
    p.add_argument("--judge_batch_size", type=int, default=20)
    p.add_argument("--no_judge", action="store_true", help="Generate IdiomCE outputs but skip judging.")
    return p


def _split_csv(s: str) -> List[str]:
    return [x.strip() for x in s.split(",") if x.strip()]


def main():
    args = build_parser().parse_args()
    tasks = [t.strip() for t in args.tasks.split(",") if t.strip()]
    unknown = set(tasks) - set(LOADERS)
    if unknown:
        raise SystemExit(f"Unknown tasks: {sorted(unknown)}; choose from {sorted(LOADERS)}")

    os.makedirs(args.output_dir, exist_ok=True)
    run_name = args.run_name or os.path.basename(os.path.normpath(args.model_path))

    logger.info("Loading model under test: %s", args.model_path)
    model = HFModel(args.model_path, dtype=args.dtype, max_length=args.max_length)

    summary: Dict[str, Any] = {"run_name": run_name, "model_path": args.model_path, "tasks": {}}

    for name in tasks:
        logger.info("=== Task: %s ===", name)
        if name == "mabl":
            task = LOADERS[name](args.mabl_path, num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name == "global_piqa":
            task = LOADERS[name](args.global_piqa_path, num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name == "milu":
            task = LOADERS[name](args.milu_path, num_fewshot=args.milu_num_fewshot,
                                 limit=args.limit, seed=args.seed,
                                 fewshot_path=args.milu_fewshot_path)
        elif name == "idiomce":
            task = LOADERS[name](args.idiomce_path, limit=args.limit)
        elif name == "mmlu":
            task = LOADERS[name](args.mmlu_path, num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name == "boolq":
            task = LOADERS[name](args.boolq_path, num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name == "chid":
            task = LOADERS[name](args.chid_path, answer_path=args.chid_answer_path,
                                 num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name == "chengyu_bench":
            task = LOADERS[name](args.chengyu_bench_dir,
                                 subtask=args.chengyu_bench_subtask,
                                 num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name == "cmmlu":
            subjects = ([s.strip() for s in args.cmmlu_subjects.split(",") if s.strip()]
                        if args.cmmlu_subjects else None)
            task = LOADERS[name](subjects=subjects, num_fewshot=args.cmmlu_num_fewshot,
                                 cmmlu_dir=args.cmmlu_dir, limit=args.limit, seed=args.seed)
        elif name == "ccpm":
            task = LOADERS[name](args.ccpm_path, num_fewshot=args.num_fewshot,
                                 limit=args.limit, seed=args.seed)
        elif name in LOADERS_AR:
            # Every Arabic loader shares (ar_data_dir, num_fewshot, limit, seed, kb_path);
            # task-specific selectors are passed only where they exist.
            kw = dict(ar_data_dir=args.ar_data_dir, num_fewshot=args.ar_num_fewshot,
                      limit=args.limit, seed=args.seed, kb_path=args.ar_kb_path)
            if name == "arabculture" and args.arabculture_countries:
                kw["countries"] = _split_csv(args.arabculture_countries)
            elif name == "arabic_cultural_qa":
                kw["dialects"] = _split_csv(args.acqa_dialects)
            elif name == "arabicmmlu" and args.arabicmmlu_subjects:
                kw["subjects"] = _split_csv(args.arabicmmlu_subjects)
            elif name == "global_piqa_ar":
                kw["cultural_only"] = not args.global_piqa_ar_all
            elif name == "kinayat_cloze":
                kw["symmetric_only"] = args.kinayat_symmetric
            task = LOADERS[name](**kw)

        if name in MC_TASKS:
            out = eval_mc(model, task, batch_size=args.batch_size)
        else:
            out = eval_gen(model, task, args)

        # Persist per-task detail + fold metrics into the summary.
        with open(os.path.join(args.output_dir, f"{name}.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        summary["tasks"][name] = out["metrics"]
        logger.info("%s -> %s", name, json.dumps(out["metrics"], ensure_ascii=False))

    with open(os.path.join(args.output_dir, "summary.json"), "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)
    logger.info("Wrote summary to %s", os.path.join(args.output_dir, "summary.json"))
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
