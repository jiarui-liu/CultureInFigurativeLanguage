@dataclass
class SourceSpec:
    """One upstream dataset and how to turn its rows into KB records."""
    name: str
    hf_id: str
    adapter: Callable[[Dict[str, Any]], Optional[Dict[str, Any]]]
    files: Optional[List[str]] = None      # data_files for load_dataset
    split: str = "train"
    variety: str = NAN                     # default dialect label
    provenance: Dict[str, str] = field(default_factory=dict)
    note: str = ""


# --------------------------------------------------------------------------- #
# Source-text cleaning — defects found by the entry-by-entry LLM audit
# --------------------------------------------------------------------------- #
# Shamela printed-page markers, e.g. ⦗٢٣٨⦘ — 535 entries (5.0%), all from the
# al-Maydani classical file. They appear both inside glosses and inside headwords.
_RE_PAGE_MARKER = re.compile(r"⦗[^⦘]{0,12}⦘")
# Bidi controls (LRM/RLM/embedding) — 332 entries (3.1%), almost all Tunisian.
_RE_BIDI = re.compile(r"[‎‏‪-‮⁦-⁩]")
# HTML scrape residue: hard newlines + long indentation runs — 5,488 entries
# (51.7%), the single largest mechanical defect. Present in both idiom strings
# (splitting them across lines) and glosses.
_RE_WS = re.compile(r"\s+")
# A trailing footnote numeral left by the scrape, e.g. "...يقلعه ١٩" or "»٨٩".
_RE_TRAILING_FOOTNOTE = re.compile(r"\s*[»«]?\s*[٠-٩\d]{1,3}\s*$")
# Glosses that state no meaning at all.
_RE_NO_MEANING = re.compile(
    r"^\s*(?:معناه\s+ظاهر|المعنى\s+ظاهر|معناها\s+ظاهر)\s*[.。]?\s*$"
)
_RE_CROSSREF_ONLY = re.compile(r"^\s*(?:انظر|راجع|وانظر)\s*[:：]")
# Verbs/markers that introduce an actual gloss. If a cross-reference also carries
# one of these, it is stating a meaning as well as pointing elsewhere — keep it.
_RE_HAS_GLOSS = re.compile(r"يضرب|يقال|كناية|معناه|معناها|المراد|يريدون|أي\s")


def clean_source_text(s: str, *, strip_footnote: bool = False) -> str:
    """Remove scrape artefacts from one source string.

    All of these were found by auditing the built KB entry by entry; each is a
    deterministic, content-preserving removal (nothing meaningful is dropped).
    """
    if not s:
        return ""
    s = _RE_PAGE_MARKER.sub(" ", s)
    s = _RE_BIDI.sub("", s)
    s = _RE_WS.sub(" ", s).strip()
    if strip_footnote:
        s = _RE_TRAILING_FOOTNOTE.sub("", s).strip()
    return s


# al-Maydani lists a head proverb and then its variant forms inline, in quotes:
#   أَضَلُّ مِنْ ضَبٍّ، و"مِنْ وَرَلٍ"و"مِنْ وَلَدِ الْيَرْبُوعِ"
# and sometimes an editorial citation:  ...اليقِينُ(انظر الفاخر ١.٢)قال هشام
# Left in the `idiom` field this is not merely untidy — the surface never occurs
# in running text, so the corpus matcher scores ZERO recall on those entries.
# Split the head off and keep the variants in `meta.idiom_variants` (lossless).
# NB the waw may carry a diacritic (وَ"...") and the variant may be introduced by a
# guillemet instead of a quote. Requiring a bare `و"` missed 7 of the 16 cases.
_HARAKAT = r"[ً-ْٰ]*"
_RE_VARIANT_TAIL = re.compile(
    rf"[،,؛;]\s*و{_HARAKAT}\s*(?=[\"«“])"      # ...، و"variant"   /   ...، وَ"variant"
    rf"|\s*،?\s*ويقال{_HARAKAT}\s*(?=[\"«“])"  # ...، ويقال"variant"
    rf"|\s+(?=«)"                              # ...المثل « variant
)
_RE_EDITORIAL = re.compile(r"\s*\((?:انظر|راجع)[^)]*\)\s*.*$")
# A lone quote left dangling at an EDGE, either after the head is split off or
# present in the source (…وَالجَمَلْ مَا شَالهُمْ"). It breaks corpus matching.
# Edges only, deliberately: an INTERIOR quote is doing word-separation work in
# these scraped entries, and deleting it glues words together — stripping every
# quote turned وأظنه"إنا into وأظنهإنا and معه"مِنْ"نحو into معهمِنْنحو.
_RE_STRAY_QUOTE = re.compile(r"^[\"«»“”„‟']+|[\"«»“”„‟']+$")


def split_variant_furniture(idiom: str) -> tuple:
    """``idiom`` -> (head_idiom, [variant strings]). No-op when there is no tail."""
    if not idiom:
        return "", []
    s = _RE_EDITORIAL.sub("", idiom).strip()
    m = _RE_VARIANT_TAIL.search(s)
    if not m:
        # No variant tail, but a dangling quote may still be present.
        return _RE_STRAY_QUOTE.sub("", s).strip(" ،,؛;"), []
    head, tail = s[:m.start()].strip(" ،,؛;"), s[m.start():]
    variants = [v.strip() for v in re.findall(r"[\"«“]([^\"»”]+)[\"»”]?", tail) if v.strip()]
    head = _RE_STRAY_QUOTE.sub("", head).strip(" ،,؛;")
    return (head or s), variants


def is_contentless_meaning(s: str) -> bool:
    """True for glosses that assert no meaning (fails inclusion criterion 2).

    Two attested patterns: ``معناه ظاهر`` ("its meaning is obvious", 13 entries)
    and a bare cross-reference ``انظر: «...»`` (142 entries) that defers to
    another headword without stating anything.
    """
    s = (s or "").strip()
    if not s:
        return True
    if _RE_NO_MEANING.match(s):
        return True
    # A cross-reference is contentless only if it merely points elsewhere. If it
    # ALSO carries a gloss marker (يضرب / يقال / كناية / معناه / أي), it states a
    # meaning too and is kept. This is more principled than a length cutoff.
    return bool(_RE_CROSSREF_ONLY.match(s)) and not _RE_HAS_GLOSS.search(s)


def _clean(v: Any) -> str:
    """Coerce a cell to a stripped string; '', None, 'nan' -> ''."""
    if v is None:
        return ""
    s = clean_source_text(str(v))
    return "" if s.lower() in {"", "nan", "none", "null"} else s


def _as_list(v: Any) -> List[str]:
    """Wrap a scalar/……list into a list of non-empty strings."""
    if v is None:
        return []
    if isinstance(v, (list, tuple)):
        out = [_clean(x) for x in v]
    else:
        out = [_clean(v)]
    return [x for x in out if x]


# ---- adapters (one per upstream schema) ----------------------------------- #
def _ad_tahaalselwii(row):
    """`Arabic Proverb`, `Explanation` (Arabic prose)."""
    idiom = _clean(row.get("Arabic Proverb") or row.get("Arabic-Proverb"))
    expl = _clean(row.get("Explanation"))
    if not idiom:
        return None
    return {"idiom": idiom, "figurative_meanings": _as_list(expl)}


def _ad_jawaher(row):
    """`Proverbs`, `Ar_Explanation`, `En_Explanation`, `En_Equivalent`, `Variety`."""
    idiom = _clean(row.get("Proverbs"))
    if not idiom:
        return None
    # Jawaher's English is HUMAN (verified: 710/1017 unique equivalents, max reuse
    # 8x, genuine idiomatic matches like "Blood is thicker than water"). Keep it,
    # but in its own field — mixing English into figurative_meanings polluted an
    # Arabic-only field and the audit flagged it on every Jawaher entry.
    return {"idiom": idiom,
            "figurative_meanings": _as_list(row.get("Ar_Explanation")),
            "figurative_meanings_en": (_as_list(row.get("En_Explanation"))
                                       + _as_list(row.get("En_Equivalent"))),
            "variety": _clean(row.get("Variety")) or NAN}


def _ad_kinayat(row):
    """`Idiom`, `Ar_Explanation`, `full_sentence` (only 150/325 rows have a sentence).

    ``Incorrect_Explanation`` is a deliberate distractor and is NEVER ingested.
    """
    idiom = _clean(row.get("Idiom"))
    if not idiom:
        return None
    return {"idiom": idiom,
            "figurative_meanings": _as_list(row.get("Ar_Explanation")),
            "examples": _as_list(row.get("full_sentence")),
            "variety": "EGY"}


def _ad_tunisian(row):
    """`tunisan_proverb`, `proverb_arabic_explaination`, `dynamic` (En equivalent).

    ``caption_formal``/``prompt``/``dynamic`` are machine-translated noise, dropped.
    """
    idiom = _clean(row.get("tunisan_proverb"))
    if not idiom:
        return None
    # `dynamic` is DROPPED: the audit showed it is machine-produced boilerplate —
    # "no good deed goes unpunished" recycled across 9 unrelated proverbs, plus
    # literal-MT nonsense ("the genie and the genie", "from a sugar cane") and one
    # degenerate repetition loop. That fails inclusion criterion 1.
    return {"idiom": idiom,
            "figurative_meanings": _as_list(row.get("proverb_arabic_explaination")),
            "variety": "TUN"}


def _ad_absher(row):
    """`Term`, `Meaning_of_term`, `Dialect type`. Rows repeat across 6 MCQ files.

    Absher is a crowd-sourced dialect GLOSSARY, not an idiom list: the audit found
    12-14 of every ~20 sampled entries were bare lemmas (خندريس، مطانيج، زين، فقع)
    with one-word definitions. We keep only multi-word entries, which is the
    strongest signal available without per-entry judgement.
    """
    idiom = _clean(row.get("Term"))
    if not idiom or len(idiom.split()) < MIN_IDIOM_TOKENS:
        return None
    return {"idiom": idiom,
            "figurative_meanings": _as_list(row.get("Meaning_of_term")),
            "variety": f"SAU/{_clean(row.get('Dialect type')) or 'General'}"}


def _ad_hassaniya(row):
    """Alpaca format: `input` = proverb, `output` = meaning."""
    idiom = _clean(row.get("input"))
    if not idiom:
        return None
    return {"idiom": idiom, "figurative_meanings": _as_list(row.get("output")),
            "variety": "MAU"}


