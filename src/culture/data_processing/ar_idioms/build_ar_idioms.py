# Which register wins when one idiom is attested in several sources.
_REGISTER_RANK = {"classical": 3, "msa": 2, "colloquial": 1}


def resolve_varieties(raw_labels: List[str]) -> Dict[str, Any]:
    """Map raw source labels to ISO codes / region names / a single register."""
    codes, regions, registers, unknown = [], [], [], []
    for lab in raw_labels:
        hit = VARIETY_MAP.get(lab)
        if hit is None:
            unknown.append(lab)
            continue
        code, region, reg = hit
        if code != NAN and code not in codes:
            codes.append(code)
        if region not in regions:
            regions.append(region)
        registers.append(reg)
    register = max(registers, key=lambda r: _REGISTER_RANK.get(r, 0)) if registers else NAN
    return {"variety": codes or NAN, "variety_region": regions or NAN,
            "register": register, "unknown_labels": unknown}


# --------------------------------------------------------------------------- #
# Record assembly
# --------------------------------------------------------------------------- #
FIELDS = ["entities", "literal_meanings", "figurative_meanings",
          "figurative_meanings_en", "examples"]


def make_record(parsed: Dict[str, Any], spec: SourceSpec) -> Optional[Dict[str, Any]]:
    """Normalize one adapter output into the KB record shape, or None if invalid."""
    # Strip the quote furniture dictionaries wrap around headwords BEFORE storing:
    # every one of the 3,187 Taymur colloquial proverbs is «...», and those
    # characters never occur around the proverb in running text.
    idiom = _clean(parsed.get("idiom"))
    # Trailing scrape footnote (e.g. «...»٨٩) then wrapping quote furniture.
    idiom = strip_quote_furniture(clean_source_text(idiom, strip_footnote=True))
    # al-Maydani appends variant forms in quotes after the head proverb. Keeping
    # them in `idiom` makes the surface unmatchable in running text (zero corpus
    # recall for those entries), so split them off and preserve them separately.
    idiom, idiom_variants = split_variant_furniture(idiom)
    if not idiom or not looks_arabic(idiom):
        return None
    if len(idiom.split()) < MIN_IDIOM_TOKENS:
        return None

    # Drop glosses that state no meaning ("معناه ظاهر", bare "انظر: ...").
    fig = [m for m in _as_list(parsed.get("figurative_meanings"))
           if not is_contentless_meaning(m)]
    lit = [m for m in _as_list(parsed.get("literal_meanings"))
           if not is_contentless_meaning(m)]
    rec = {
        "idiom": idiom,
        "entities": _as_list(parsed.get("entities")),
        "literal_meanings": lit,
        "figurative_meanings": fig,
        "figurative_meanings_en": _as_list(parsed.get("figurative_meanings_en")),
        "examples": _as_list(parsed.get("examples")),
        "_variety": parsed.get("variety") or spec.variety,
        "_source": spec.name,
        "_idiom_variants": idiom_variants,
    }
    # Criterion 2: at least one meaning.
    if not rec["literal_meanings"] and not rec["figurative_meanings"]:
        return None
    return rec


def merge_records(records: Iterable[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Merge across sources, keyed on the NORMALIZED idiom form.

    Same proverb, different vocalization/orthography → one entry whose field lists
    are the de-duplicated union, with provenance accumulated in ``meta``.
    """
    merged: Dict[str, Dict[str, Any]] = {}
    for rec in records:
        key = normalize_ar(rec["idiom"])
        if not key:
            continue
        cur = merged.get(key)
        if cur is None:
            merged[key] = {
                "idiom": rec["idiom"],
                **{f: list(rec[f]) for f in FIELDS},
                "_varieties": [rec["_variety"]] if rec["_variety"] != NAN else [],
                "_sources": [rec["_source"]],
            }
            continue
        # Prefer the longer surface form as canonical (usually the vocalized one,
        # which carries more information for display/tagging).
        if len(rec["idiom"]) > len(cur["idiom"]):
            cur["idiom"] = rec["idiom"]
        for f in FIELDS:
            for v in rec[f]:
                if v not in cur[f]:
                    cur[f].append(v)
        if rec["_variety"] != NAN and rec["_variety"] not in cur["_varieties"]:
            cur["_varieties"].append(rec["_variety"])
        if rec["_source"] not in cur["_sources"]:
            cur["_sources"].append(rec["_source"])
    return list(merged.values())


def to_output_record(m: Dict[str, Any], index: int) -> Dict[str, Any]:
    """Final on-disk shape, mirroring the Chinese KB. Empty fields become ``"NAN"``.

    Arabic additionally carries ``variety``/``variety_region``/``register`` inside
    ``output`` — a deliberate divergence from the zh/en schema, because an Arabic
    idiom belongs to a specific variety in a way a chengyu does not.
    """
    v = resolve_varieties(m["_varieties"])
    out = {"idiom": m["idiom"]}
    for f in FIELDS:
        out[f] = m[f] if m[f] else NAN
    out["variety"] = v["variety"]
    out["variety_region"] = v["variety_region"]
    out["register"] = v["register"]
    meta = {
        "sources": m["_sources"],
        "varieties_raw": m["_varieties"] or NAN,   # source labels, for traceability
    }
    if v["unknown_labels"]:
        meta["unmapped_variety_labels"] = v["unknown_labels"]
    return {"idiom": m["idiom"], "index": index, "output": out, "meta": meta}


