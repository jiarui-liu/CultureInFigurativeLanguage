def self_test() -> int:
    """Exercise every adapter + the criteria + dedup on fixtures. No network."""
    spec_by_name = {s.name: s for s in SOURCES}

    # --- adapters ---------------------------------------------------------- #
    r = _ad_tahaalselwii({"Arabic Proverb": "أهل مكة أدرى بشعابها",
                          "Explanation": "يضرب لمن هو أعلم بشأنه"})
    assert r["idiom"] == "أهل مكة أدرى بشعابها" and len(r["figurative_meanings"]) == 1

    r = _ad_jawaher({"Proverbs": " إنك لا تجني من الشوك العنب",
                     "Ar_Explanation": "يضرب لمن يصنع المعروف في غير أهله",
                     "En_Explanation": "Doing good to the wrong people.",
                     "En_Equivalent": "You can't make a silk purse out of a sow's ear.",
                     "Variety": "MSA"})
    # English now lives in its OWN field; the Arabic field stays Arabic-only.
    assert r["variety"] == "MSA"
    assert r["figurative_meanings"] == ["يضرب لمن يصنع المعروف في غير أهله"]
    assert len(r["figurative_meanings_en"]) == 2
    assert "English equivalent" not in json.dumps(r, ensure_ascii=False)

    r = _ad_kinayat({"Idiom": "خَبَرَ أبْيَضْ", "Ar_Explanation": "كناية عن الخبر السيئ",
                     "Incorrect_Explanation": "DISTRACTOR — must not appear",
                     "full_sentence": "يا خَبَرَ أبْيَضْ! ايه اللي هو عمله ده."})
    assert r["examples"] == ["يا خَبَرَ أبْيَضْ! ايه اللي هو عمله ده."]
    assert "DISTRACTOR" not in json.dumps(r, ensure_ascii=False)   # never ingested

    r = _ad_kinayat({"Idiom": "أَجْرِ مْنَاوِلْ", "Ar_Explanation": "معناه كذا",
                     "full_sentence": ""})          # 175/325 rows have no sentence
    assert r["examples"] == []

    r = _ad_tunisian({"tunisan_proverb": "إذا تقول البلوط أحلى من التمر",
                      "proverb_arabic_explaination": "يقصد به المداهن",
                      "caption_formal": "MT GARBAGE", "dynamic": "people always talk"})
    # BOTH machine columns dropped: caption_formal AND dynamic (recycled boilerplate).
    assert "MT GARBAGE" not in json.dumps(r, ensure_ascii=False)
    assert "people always talk" not in json.dumps(r, ensure_ascii=False)
    assert r["figurative_meanings"] == ["يقصد به المداهن"]

    r = _ad_absher({"Term": "إذا حجت البقرة على قرونها",
                    "Meaning_of_term": "بمعنى المستحيل", "Dialect type": "General"})
    assert r["variety"] == "SAU/General"
    # Absher is a dialect glossary: bare lemmas are rejected outright.
    assert _ad_absher({"Term": "خندريس", "Meaning_of_term": "نوع من التمر"}) is None
    assert _ad_absher({"Term": "زين", "Meaning_of_term": "جميل"}) is None

    r = _ad_hassaniya({"input": "ألْبَلْ تبرك على أكبارها",
                       "output": "يضرب لأهمية الكبار في مجتمعهم"})
    assert r["variety"] == "MAU"

    # --- scrape-artefact cleaning (found by the entry-by-entry LLM audit) ---- #
    assert clean_source_text("قال ⦗٢٣٨⦘ الشيء") == "قال الشيء"        # page marker
    assert clean_source_text("\u200fمثل عربي") == "مثل عربي"            # RLM
    assert clean_source_text("مثل\n                   عربي") == "مثل عربي"  # HTML
    assert clean_source_text("يقلعه ١٩", strip_footnote=True) == "يقلعه"
    assert clean_source_text("") == ""

    # contentless glosses (criterion 2)
    assert is_contentless_meaning("معناه ظاهر")
    assert is_contentless_meaning("المعنى ظاهر.")
    assert is_contentless_meaning("انظر: «الجعان يحلم بسوق العيش»")
    assert not is_contentless_meaning("يضرب لمن هو أعلم بشأن نفسه")
    # a cross-reference WITH real content is kept
    assert not is_contentless_meaning(
        "انظر: كذا. ويضرب هذا المثل لمن يصنع المعروف في غير أهله ولا يجد جزاء")

    # a row whose only gloss is contentless is dropped by criterion 2
    s_cl = spec_by_name["tahaalselwii_colloquial"]
    assert make_record({"idiom": "مثل عربي هنا",
                        "figurative_meanings": ["معناه ظاهر"]}, s_cl) is None
    # single-token headwords are rejected everywhere
    assert make_record({"idiom": "زين", "figurative_meanings": ["جميل"]}, s_cl) is None

    # --- REGRESSION: guillemets stripped from the stored surface form ------- #
    s_col = spec_by_name["tahaalselwii_colloquial"]
    r = _ad_tahaalselwii({"Arabic Proverb": "«آخِرِ الحَيَاة الْمُوتْ»",
                          "Explanation": "حكمة جرت مجرى الأمثال"})
    rec = make_record(r, s_col)
    assert rec["idiom"] == "آخِرِ الحَيَاة الْمُوتْ", rec["idiom"]
    assert "«" not in rec["idiom"] and "»" not in rec["idiom"]

    # --- criterion 2: a row with no meaning is dropped --------------------- #
    s = spec_by_name["tahaalselwii_classical"]
    assert make_record({"idiom": "مثل بلا شرح", "figurative_meanings": []}, s) is None
    assert make_record({"idiom": "مثل عربي", "literal_meanings": ["شرح حرفي"]}, s) is not None
    # non-Arabic junk rejected
    assert make_record({"idiom": "hello world", "figurative_meanings": ["xyz"]}, s) is None

    # --- dedup across sources via normalization ---------------------------- #
    recs = [
        make_record({"idiom": "إنَّ دَوَاءَ الشَّقِّ أنْ تَحُوصَهُ",       # vocalized
                     "figurative_meanings": ["شرح كلاسيكي"]}, s),
        make_record({"idiom": "ان دواء الشق ان تحوصه",                  # bare
                     "figurative_meanings": ["شرح آخر"]},
                    spec_by_name["jawaher"]),
    ]
    merged = merge_records(recs)
    assert len(merged) == 1, f"expected dedup to 1, got {len(merged)}"
    assert merged[0]["idiom"] == "إنَّ دَوَاءَ الشَّقِّ أنْ تَحُوصَهُ"      # longer form kept
    assert len(merged[0]["figurative_meanings"]) == 2                    # union
    assert set(merged[0]["_sources"]) == {"tahaalselwii_classical", "jawaher"}

    # --- output shape + NAN filling ---------------------------------------- #
    out = to_output_record(merged[0], 0)
    assert set(out["output"]) == {"idiom", *FIELDS,
                                  "variety", "variety_region", "register"}
    assert out["output"]["entities"] == NAN          # nothing supplies entities
    assert out["output"]["examples"] == NAN
    assert out["output"]["figurative_meanings"] != NAN
    assert out["index"] == 0 and out["idiom"] == merged[0]["idiom"]

    # Chinese-KB parity: same top-level keys plus `examples`, variety, `meta`.
    zh_output_keys = {"idiom", "entities", "literal_meanings", "figurative_meanings"}
    assert zh_output_keys <= set(out["output"])

    # --- Arabic variety labelling ------------------------------------------ #
    v = resolve_varieties(["EGY"])
    assert v == {"variety": ["arz"], "variety_region": ["Egyptian"],
                 "register": "colloquial", "unknown_labels": []}, v
    # register is separated from variety, and classical outranks colloquial
    assert resolve_varieties(["Classical/MSA"])["register"] == "classical"
    assert resolve_varieties(["Classical/MSA", "EGY"])["register"] == "classical"
    # Levantine countries collapse onto the right ISO codes
    assert resolve_varieties(["SYR", "LEB"])["variety"] == ["apc"]
    assert resolve_varieties(["PAL", "JOR"])["variety"] == ["ajp"]
    # Gulf states share afb; Oman does not
    assert resolve_varieties(["UAE", "QAT", "KUW", "BAH"])["variety"] == ["afb"]
    assert resolve_varieties(["OMA"])["variety"] == ["acx"]
    # No confident ISO code -> NAN, but the region is still recorded (no guessing)
    g = resolve_varieties(["SAU/General"])
    assert g["variety"] == NAN and g["variety_region"] == ["Saudi (unspecified)"]
    # Every label the sources actually emit must be mapped
    for lab in ["Classical/MSA", "MSA", "EGY", "TUN", "MAU", "SAU", "SAU/Central",
                "SAU/Western", "SAU/General", "SAU/Southern", "SAU/Northern",
                "SAU/Eastern", "UAE", "ALG", "SUD", "KUW", "PAL", "SYR", "YEM",
                "LIB", "QAT", "OMA", "JOR", "BAH", "IRQ", "MOR", "LEB"]:
        assert lab in VARIETY_MAP, f"unmapped source label: {lab}"

    # --- coverage stats ----------------------------------------------------- #
    st = coverage([out])
    assert st["total"] == 1 and st["figurative_meanings"]["have"] == 1
    assert st["examples"]["nan"] == 1

    # --- drop-llm-assisted blanks Kinayat examples -------------------------- #
    ks = spec_by_name["kinayat"]
    assert ks.provenance["examples"] == "llm_generated_human_reviewed"

    print("all build_ar_idioms.py self-tests passed")
    return 0


