#!/usr/bin/env python3
"""Build the merged Arabic idiom knowledge base.

Produces ``data/idioms/ar/idioms_merged_llm_formatted.jsonl`` with the same shape
as the Chinese KB (``data/idioms/zh/idioms_merged_llm_formatted.jsonl``) plus an
``examples`` field::

    {"idiom": ..., "index": N,
     "output": {"idiom", "entities", "literal_meanings",
                "figurative_meanings", "examples"},
     "meta":   {"sources", "varieties", "source_refs"}}

Any field with no valid value is written as the string ``"NAN"``.

INCLUSION CRITERIA (enforced in code, not by convention)
--------------------------------------------------------
1. **Human-authored only.** The idiom *and* its meaning explanations must be
   written by humans, not generated by an AI. Sources that fail this are listed in
   :data:`EXCLUDED_SOURCES` with the reason, and are never fetched.
2. **At least one meaning.** A row is dropped unless it has a non-empty
   ``figurative_meanings`` *or* ``literal_meanings``.

Per-field provenance is recorded so a partially-machine-assisted field can be
audited later (see ``FIELD_PROVENANCE`` and the ``--drop-llm-assisted`` flag).

Deduplication uses :func:`culture.data_processing.ar_idioms.normalize.normalize_ar`
so that vocalized and unvocalized spellings of the same proverb collapse together —
without it, the same proverb appears several times across sources.

Usage::

    python -m culture.data_processing.ar_idioms.build_ar_idioms \\
        --out data/idioms/ar/idioms_merged_llm_formatted.jsonl

    python -m culture.data_processing.ar_idioms.build_ar_idioms --self-test
"""

