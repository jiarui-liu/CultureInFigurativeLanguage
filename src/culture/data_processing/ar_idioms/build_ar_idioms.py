def _parse_file(path: str) -> List[Dict[str, Any]]:
    """Parse one downloaded data file by extension."""
    ext = os.path.splitext(path)[1].lower()
    if ext == ".jsonl":
        with open(path, encoding="utf-8") as f:
            return [json.loads(l) for l in f if l.strip()]
    if ext == ".json":
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, list) else data.get("data", [])
    if ext in (".csv", ".tsv"):
        # utf-8-SIG, not utf-8: the tahaalselwii CSVs carry a UTF-8 BOM, which
        # otherwise lands inside the first column name ('﻿Arabic Proverb')
        # and silently made every adapter lookup miss — all 7,730 rows dropped.
        with open(path, encoding="utf-8-sig", newline="") as f:
            return list(csv.DictReader(f, delimiter="\t" if ext == ".tsv" else ","))
    raise ValueError(f"Unsupported data file extension: {path}")


def load_source(spec: SourceSpec, cache_dir: Optional[str] = None) -> List[Dict[str, Any]]:
    """Fetch a source by downloading its data files directly from the Hub.

    Deliberately NOT ``datasets.load_dataset``. Three of these repos break it:

    * ``Tunisian-Proverbs-…`` ships **5,189 PNGs and a ``dataset.py`` loading
      script**, so ``load_dataset`` stalls resolving the whole repo — we only
      want the one 999-row CSV.
    * ``Jawaher-benchmark`` declares train/test splits in its card, so passing
      custom ``data_files`` raises ``ExpectedMoreSplitsError: {'test'}``.
    * ``Absher-Benchmark`` stores the same terms across six MCQ task files.

    Pulling named files with ``hf_hub_download`` sidesteps all of it, is
    reproducible, and drops the heavyweight ``datasets`` dependency.
    """
    from huggingface_hub import hf_hub_download

    if not spec.files:
        raise ValueError(f"{spec.name}: `files` must be listed explicitly")
    rows: List[Dict[str, Any]] = []
    for fname in spec.files:
        path = hf_hub_download(spec.hf_id, fname, repo_type="dataset",
                               cache_dir=cache_dir)
        got = _parse_file(path)
        logger.info("  %s <- %s (%d rows)", spec.name, fname, len(got))
        rows.extend(got)
    return rows


def build(specs: List[SourceSpec], cache_dir: Optional[str] = None,
          drop_llm_assisted: bool = False) -> tuple:
    """Fetch + adapt + filter every source. Returns (records, per-source report)."""
    records: List[Dict[str, Any]] = []
    report: List[Dict[str, Any]] = []
    for spec in specs:
        try:
            rows = load_source(spec, cache_dir)
        except Exception as e:  # noqa: BLE001 — one bad source must not kill the build
            logger.error("FAILED to load %s (%s): %s", spec.name, spec.hf_id, e)
            report.append({"source": spec.name, "status": "FAILED", "error": str(e)})
            continue

        kept = dropped_no_meaning = dropped_bad = 0
        for row in rows:
            parsed = spec.adapter(row)
            if parsed is None:
                dropped_bad += 1
                continue
            if drop_llm_assisted:
                for f, prov in spec.provenance.items():
                    if prov != "human" and f in parsed:
                        parsed[f] = []
            rec = make_record(parsed, spec)
            if rec is None:
                dropped_no_meaning += 1
                continue
            records.append(rec)
            kept += 1

        logger.info("%-24s rows=%-7d kept=%-7d dropped(no meaning/invalid)=%d/%d",
                    spec.name, len(rows), kept, dropped_no_meaning, dropped_bad)
        report.append({"source": spec.name, "hf_id": spec.hf_id, "status": "ok",
                       "rows": len(rows), "kept": kept,
                       "dropped_no_meaning": dropped_no_meaning,
                       "dropped_invalid": dropped_bad, "note": spec.note})
    return records, report


def coverage(out_records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Field-coverage stats for the final KB."""
    n = len(out_records)
    stats = {"total": n}
    for f in FIELDS:
        have = sum(1 for r in out_records if r["output"][f] != NAN)
        stats[f] = {"have": have, "nan": n - have,
                    "pct": round(100.0 * have / n, 2) if n else 0.0}
    return stats


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", default="data/idioms/ar/idioms_merged_llm_formatted.jsonl")
    p.add_argument("--report", default=None, help="Write the build report JSON here.")
    p.add_argument("--sources", default=None,
                   help="Comma-separated subset of source names (default: all).")
    p.add_argument("--cache_dir", default=None)
    p.add_argument("--drop-llm-assisted", action="store_true",
                   help="Blank any field whose provenance is not 'human' (strictest "
                        "reading of criterion 1; drops Kinayat's usage sentences).")
    p.add_argument("--self-test", action="store_true",
                   help="Run offline adapter/merge tests on fixtures; no network.")
    return p


def main() -> int:
    args = build_parser().parse_args()
    if args.self_test:
        return self_test()

    specs = SOURCES
    if args.sources:
        want = {s.strip() for s in args.sources.split(",") if s.strip()}
        unknown = want - {s.name for s in SOURCES}
        if unknown:
            raise SystemExit(f"Unknown sources: {sorted(unknown)}")
        specs = [s for s in SOURCES if s.name in want]

    logger.info("Excluded by criterion 1 (AI-generated / not Arabic idioms):")
    for k, v in EXCLUDED_SOURCES.items():
        logger.info("  - %s: %s", k, v)

    records, report = build(specs, args.cache_dir, args.drop_llm_assisted)

    # Fail loudly rather than silently shipping an empty/partial KB.
    failed = [r for r in report if r.get("status") == "FAILED"]
    if not records:
        for r in failed:
            logger.error("  %s -> %s", r["source"], r.get("error"))
        raise SystemExit(
            f"ABORT: no records loaded ({len(failed)}/{len(report)} sources failed). "
            "Is `datasets` installed and is the network reachable?"
        )
    if failed:
        logger.warning("%d/%d sources FAILED to load — the KB below is INCOMPLETE: %s",
                       len(failed), len(report), [r["source"] for r in failed])

    merged = merge_records(records)
    out_records = [to_output_record(m, i) for i, m in enumerate(merged)]

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for r in out_records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    stats = coverage(out_records)
    logger.info("Wrote %d unique idioms to %s (from %d raw records; %d merged away)",
                len(out_records), out_path, len(records), len(records) - len(out_records))
    logger.info("Field coverage: %s", json.dumps(stats, ensure_ascii=False))

    if args.report:
        Path(args.report).parent.mkdir(parents=True, exist_ok=True)
        with open(args.report, "w", encoding="utf-8") as f:
            json.dump({"sources": report, "coverage": stats,
                       "excluded": EXCLUDED_SOURCES}, f, ensure_ascii=False, indent=2)
        logger.info("Wrote report to %s", args.report)

    print(json.dumps(stats, ensure_ascii=False, indent=2))
    return 0


