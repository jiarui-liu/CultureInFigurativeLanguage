#!/usr/bin/env python3
"""Independent evidence audit for the cross-cultural symbolism probe.

The original probe was generated by Qwen3.5-27B and verified by Gemma-4-26B.
This script asks a third model family to identify, from the underlying idioms,
which option is supported only in the target language and which is supported
only in English. Model predictions are never shown to the auditor. The output
therefore supports a consensus subset fixed independently of evaluation results.
"""

from __future__ import annotations

import argparse
import json
import os
import re
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

from culture.analysis.v2.metagen_api import generate
from culture.data_processing.ar_idioms.normalize import normalize_ar


LANGUAGE_NAMES = {"ar": "Arabic", "hi": "Hindi", "zh": "Chinese"}


def flatten(value):
    if not value or value == "NAN":
        return []
    if isinstance(value, str):
        return [value]
    out = []
    for item in value:
        out.extend(flatten(item))
    return out


def normalize_entity(entity: str, lang: str) -> str:
    entity = entity.strip()
    if lang == "en":
        return entity.lower()
    if lang == "ar":
        entity = normalize_ar(entity)
        if entity in {"الله", "لله", "والله", "بالله"}:
            return "الله"
        return re.sub(r"^(ال|لل)", "", entity)
    return entity


def load_index(repo: Path, lang: str) -> dict[str, list[dict]]:
    suffix = "idioms_merged_llm_formatted.jsonl" if lang == "ar" else "idioms_merged_llm_formatted_figurative_only.jsonl"
    path = repo / "culture" / "data" / "idioms" / lang / suffix
    index: dict[str, list[dict]] = defaultdict(list)
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            row = json.loads(line)
            content = row.get("output", row)
            meanings = flatten(content.get("figurative_meanings"))
            if not meanings:
                continue
            record = {"idiom": content.get("idiom", row.get("idiom", "")), "meaning": "; ".join(meanings)[:500]}
            for entity in content.get("entities", []) if isinstance(content.get("entities"), list) else []:
                index[normalize_entity(str(entity), lang)].append(record)
    return index


def parse_options(context: str) -> list[str]:
    matches = re.findall(r"(?:^|\n)[ABCD][\.．](.*?)(?=\n[ABCD][\.．]|\n(?:الإجابة|उत्तर|答案)|$)", context, flags=re.S)
    return [m.strip() for m in matches]


def evidence_text(records: list[dict], limit: int = 15) -> str:
    return "\n".join(f"- {r['idiom']}: {r['meaning']}" for r in records[:limit])


def prompt(item: dict, target_records: list[dict], english_records: list[dict], lang: str) -> str:
    options = parse_options(item["context"])
    rendered_options = "\n".join(f"{chr(65 + i)}. {option}" for i, option in enumerate(options))
    return f"""You are independently auditing a multiple-choice item about cultural symbolism in idioms. Use only the idiom evidence below. Do not use general world knowledge.

Entity in {LANGUAGE_NAMES[lang]}: {item['meta']['entity']}
Entity in English: {item['meta']['entity_en']}

{LANGUAGE_NAMES[lang]} idioms and meanings:
{evidence_text(target_records)}

English idioms and meanings:
{evidence_text(english_records)}

Candidate associations, written in {LANGUAGE_NAMES[lang]}:
{rendered_options}

Choose one option that is best supported by the {LANGUAGE_NAMES[lang]} idioms and not by the English idioms. Choose one different option that is best supported by the English idioms and not by the {LANGUAGE_NAMES[lang]} idioms. If the evidence does not support a unique choice, mark the item invalid. Return JSON only with keys target_option, english_option, valid, and reason. Option values must be A, B, C, or D."""


def parse_json(text: str) -> dict:
    try:
        start, end = text.find("{"), text.rfind("}")
        return json.loads(text[start : end + 1]) if start >= 0 and end >= start else {}
    except Exception:
        return {}


def paired_p(a: np.ndarray, b: np.ndarray) -> float:
    wins = int(np.sum((a == 1) & (b == 0)))
    losses = int(np.sum((a == 0) & (b == 1)))
    return float(binomtest(wins, wins + losses, 0.5).pvalue) if wins + losses else 1.0


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[4])
    parser.add_argument("--mc-root", type=Path, default=Path("/lustre-storage/fsx_0/user/jiaruiliu/culture-pretraining-data/eval/mc"))
    parser.add_argument("--eval-root", type=Path, default=Path("/lustre-storage/fsx_it_0/users/jiaruiliu/culture_pretraining/eval"))
    parser.add_argument("--out", type=Path, default=Path("docs/paper_stats/v3/symbolism_probe_audit.json"))
    args = parser.parse_args()

    indexes = {lang: load_index(args.repo, lang) for lang in ("en", "ar", "hi", "zh")}
    queued = []
    metadata = []
    for lang in ("ar", "hi", "zh"):
        items = [json.loads(line) for line in (args.mc_root / f"symbolism_v2_{lang}_letter.jsonl").open(encoding="utf-8")]
        for item in items:
            target_key = normalize_entity(item["meta"]["entity"], lang)
            english_key = normalize_entity(item["meta"]["entity_en"], "en")
            target_records = indexes[lang].get(target_key, [])
            english_records = indexes["en"].get(english_key, [])
            options = parse_options(item["context"])
            if len(options) != 4 or len(target_records) < 2 or len(english_records) < 2:
                metadata.append({"lang": lang, "qid": item["qid"], "item": item, "auditable": False})
                continue
            metadata.append({"lang": lang, "qid": item["qid"], "item": item, "auditable": True, "prompt_index": len(queued)})
            queued.append(prompt(item, target_records, english_records, lang))

    responses = generate(queued, tag="symbolism_probe_audit_gpt54mini_20261011", json_mode=True, max_tokens=512, workers=12)
    parsed = [parse_json(response) for response in responses]
    output = {"auditor": os.environ.get("METAGEN_MODEL", "gpt-5-4-mini-genai-responses"), "languages": {}}

    for lang in ("ar", "hi", "zh"):
        rows = []
        for meta in [m for m in metadata if m["lang"] == lang]:
            item = meta["item"]
            audit = parsed[meta["prompt_index"]] if meta["auditable"] else {}
            target = audit.get("target_option", "").strip().upper()
            english = audit.get("english_option", "").strip().upper()
            valid = bool(audit.get("valid")) and target in "ABCD" and english in "ABCD" and target != english
            agreement = valid and ord(target) - 65 == item["gold"] and ord(english) - 65 == item["meta"]["lure"]
            rows.append({"qid": item["qid"], "auditable": meta["auditable"], "valid": valid, "agreement": agreement, "target_option": target, "english_option": english, "reason": audit.get("reason", "")})

        consensus_qids = {r["qid"] for r in rows if r["agreement"]}
        arm_records = {}
        for arm in ("unfiltered", "untagged", "cpt"):
            path = args.eval_root / lang / arm / f"symbolism_v2_{lang}_letter.json"
            arm_records[arm] = {r["qid"]: r for r in json.loads(path.read_text())["records"]}
        contrasts = {}
        for arm in ("untagged", "cpt"):
            qids = sorted(consensus_qids & set(arm_records[arm]) & set(arm_records["unfiltered"]))
            a, b = arm_records[arm], arm_records["unfiltered"]
            acc_a = np.asarray([a[q]["correct"] for q in qids])
            acc_b = np.asarray([b[q]["correct"] for q in qids])
            lure_a = np.asarray([int(a[q]["pred"] == a[q]["lure"]) for q in qids])
            lure_b = np.asarray([int(b[q]["pred"] == b[q]["lure"]) for q in qids])
            margin_a = np.asarray([a[q]["logprobs"][a[q]["gold"]] - a[q]["logprobs"][a[q]["lure"]] for q in qids])
            margin_b = np.asarray([b[q]["logprobs"][b[q]["gold"]] - b[q]["logprobs"][b[q]["lure"]] for q in qids])
            contrasts[f"{arm}_minus_random"] = {"n": len(qids), "accuracy_delta": float(np.mean(acc_a - acc_b)), "accuracy_p": paired_p(acc_a, acc_b), "english_lure_delta": float(np.mean(lure_a - lure_b)), "english_lure_p": paired_p(lure_a, lure_b), "gold_lure_margin_delta": float(np.mean(margin_a - margin_b))}
        output["languages"][lang] = {"n": len(rows), "auditable": sum(r["auditable"] for r in rows), "auditor_valid": sum(r["valid"] for r in rows), "consensus": len(consensus_qids), "rows": rows, "contrasts": contrasts}

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({lang: {k: v for k, v in data.items() if k != "rows"} for lang, data in output["languages"].items()}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
